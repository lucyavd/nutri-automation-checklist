const priorityOrder: Area[] = ['helpdesk', 'access', 'reports', 'relaunch', 'reminders'];

export function getDiagnosis(answers: Record<number, string>): Diagnosis {
  const scores: Record<Area, number> = { access: 0, helpdesk: 0, reminders: 0, reports: 0, relaunch: 0 };
  questions.forEach((q, index) => {
    const selected = q.choices.find(opt => opt.id === answers[index]);
    if (selected?.issue) scores[selected.issue.area] += selected.issue.points;
  });
  const areas = priorityOrder.filter(a => scores[a] > 0)
    .sort((a,b) => scores[b] - scores[a] || priorityOrder.indexOf(a) - priorityOrder.indexOf(b));

  if (!areas.length) return {
    headline: 'Похоже, с организацией программы у тебя всё под контролем',
    insight: 'По твоим ответам явных задач, которые срочно стоит автоматизировать, не нашлось. Это не проверка всех процессов — просто нет причин предлагать тебе нового бота или приложение ради самого инструмента.',
    main: null,
    advice: '',
    additional: [],
    affectedAreas: []
  };

  const main = areas[0];
  const both = scores.access > 0 && scores.helpdesk > 0;
  const headline = both ? 'Ты случайно не администратор собственного клуба?' : resultCatalog[main].title;
  const insight = both
    ? 'Доступы, материалы и повторяющиеся вопросы могут быть связаны. Вместо трёх отдельных инструментов сначала посмотри, можно ли сделать один понятный путь для участницы — от оплаты до нужного материала.'
    : resultCatalog[main].description + ' ' + resultCatalog[main].funnyLine;
  return {
    main,
    headline,
    insight,
    advice: resultCatalog[main].next + ' ' + resultCatalog[main].solution,
    additional: areas.filter(a => a !== main),
    affectedAreas: areas
  };
}

export function getSelectedAnswer(answers: Record<number, string>, index: number): string {
  return questions[index]?.choices.find(c => c.id === answers[index])?.text || '';
}
