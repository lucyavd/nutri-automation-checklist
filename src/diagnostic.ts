export type Area = 'access' | 'helpdesk' | 'reminders' | 'reports' | 'relaunch';
export interface Choice {
  id: string;
  text: string;
  issue?: { area: Area; points: number };
}
export interface Question {
  title: string;
  choices: Choice[];
}
export interface ResultInfo {
  title: string;
  description: string;
  funnyLine: string;
  next: string;
  solution: string;
  note?: string;
}
export interface Diagnosis {
  headline: string;
  insight: string;
  main: Area | null;
  advice: string;
  additional: Area[];
  affectedAreas: Area[];
}

function choice(id: string, text: string, area?: Area, points = 0): Choice {
  return { id, text, ...(area && points > 0 ? { issue: { area, points } } : {}) };
}

